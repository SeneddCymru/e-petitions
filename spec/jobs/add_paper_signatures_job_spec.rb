require 'rails_helper'

RSpec.describe AddPaperSignaturesJob, type: :job do
  let!(:petition) { FactoryBot.create(:open_petition) }
  let(:signatures) { petition.signatures.where(creator: false).order(:id) }

  it "adds the number of signatures" do
    expect {
      perform_enqueued_jobs {
        described_class.perform_later(petition, "GB-ENG", 3, "10.0.1.1")
      }
    }.to change { petition.signatures.count }.by(3)
  end

  it "names the signatures sequentially" do
    perform_enqueued_jobs {
      described_class.perform_later(petition, "GB-ENG", 3, "10.0.1.1")
    }

    expect(signatures.map(&:name)).to eq(["Paper Signature 1", "Paper Signature 2", "Paper Signature 3"])
  end

  it "validates the signatures with the location code, paper postcode and ip address" do
    perform_enqueued_jobs {
      described_class.perform_later(petition, "GB-SCT", 2, "10.0.1.1")
    }

    signatures.each do |signature|
      expect(signature).to be_validated
      expect(signature.location_code).to eq("GB-SCT")
      expect(signature.postcode).to eq("ZZ993WZ")
      expect(signature.ip_address).to eq("10.0.1.1")
      expect(signature).to be_autogenerated_email
    end
  end

  it "generates unique email addresses" do
    perform_enqueued_jobs {
      described_class.perform_later(petition, "GB-WLS", 50, "10.0.1.1")
    }

    expect(signatures.distinct.count(:email)).to eq(50)
  end

  context "when an error occurs" do
    let(:exception) { ActiveRecord::RecordInvalid.new(Signature.new) }

    before do
      allow_any_instance_of(Signature).to receive(:save!).and_raise(exception)
    end

    it "notifies Appsignal of the error" do
      expect(Appsignal).to receive(:send_exception).with(exception)

      perform_enqueued_jobs {
        described_class.perform_later(petition, "GB-WLS", 1, "10.0.1.1")
      }
    end

    it "doesn't raise an error" do
      expect {
        perform_enqueued_jobs {
          described_class.perform_later(petition, "GB-WLS", 1, "10.0.1.1")
        }
      }.not_to raise_error
    end
  end
end
